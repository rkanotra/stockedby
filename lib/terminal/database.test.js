import test from 'node:test';
import assert from 'node:assert/strict';
import { PGlite } from '@electric-sql/pglite';
import { readFile } from 'node:fs/promises';
const owner = '11111111-1111-4111-8111-111111111111', invited = '22222222-2222-4222-8222-222222222222', outsider = '33333333-3333-4333-8333-333333333333';
test('terminal SQL isolates portfolios, locks writes, restricts jobs and deduplicates runs/alerts', async () => {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create schema auth; create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz); create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$; grant usage on schema auth to authenticated; grant execute on function auth.uid() to authenticated;`);
    await db.query('insert into auth.users values($1,$2,now()),($3,$4,now()),($5,$6,now())', [owner,'rahulkanotra1101@gmail.com',invited,'pilot@example.com',outsider,'outsider@example.com']);
    await db.exec(await readFile(new URL('../../supabase/migrations/202611030001_terminal.sql', import.meta.url), 'utf8'));
    const as = async (id, role = 'authenticated') => { await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]); await db.exec(`set role ${role}`); };
    const rpc = async (action,args = {}) => (await db.query('select terminal_command($1,$2::jsonb) result',[action,JSON.stringify(args)])).rows[0].result;
    await as(owner);
    await rpc('invite', { email: 'pilot@example.com' });
    let state = await rpc('load'); assert.equal(state.version, 1);
    await rpc('save', { version: 1, document: { positions: [{id:'fictional'}], settings: {} } });
    await assert.rejects(rpc('save', { version: 1, document: { positions: [] } }), /conflict/);
    await as(invited); assert.equal((await rpc('load')).document.positions.length, 0);
    assert.equal((await db.query('select * from terminal_portfolios')).rows.length, 1);
    await assert.rejects(rpc('invite', { email: 'other@example.com' }), /Owner/);
    await assert.rejects(db.query('select terminal_action($1,$2,$3::jsonb)',[owner,'load','{}']), /permission/);
    await as(outsider); assert.equal((await db.query('select * from terminal_portfolios')).rows.length, 0);
    await assert.rejects(rpc('load'), /access/);
    await as('', 'anon'); await assert.rejects(db.query('select * from terminal_portfolios'), /permission/);
    await assert.rejects(rpc('load'), /permission/);
    await as(owner);
    const r = await rpc('begin', { key: 'scheduled:asia:test',kind:'scheduled' });
    assert.equal((await rpc('begin', {key:'scheduled:asia:test',kind:'scheduled'})).existing,true);
    await assert.rejects(rpc('begin', {key:'other',kind:'brief'}), /Another scan/);
    await assert.rejects(rpc('finish', {...r,lease:invited,status:'complete',result:{}}), /lease/);
    await rpc('finish',{...r,status:'partial',result:{errors:['Synthetic failure']},alerts:[{key:'one',data:{title:'Test'}},{key:'one',data:{title:'Test'}}]});
    state = await rpc('load'); assert.equal(state.alerts.length,1); assert.equal(state.runs[0].status,'partial'); assert.equal(state.runs[0].lease,undefined);
    const token='fictional-test-secret-not-a-production-key-123456789';
    const hash=(await db.query("select encode(sha256(convert_to($1,'UTF8')),'hex') hash",[token])).rows[0].hash;
    await rpc('schedule',{hash,enabled:true});
    await as('', 'anon');
    const job=async(action,args={},t=token)=>(await db.query('select terminal_job($1,$2,$3::jsonb) result',[t,action,JSON.stringify(args)])).rows[0].result;
    await assert.rejects(job('load',{ownerId:owner},'incorrect'), /denied/);
    await assert.rejects(job('save',{ownerId:owner}), /denied/);
    await assert.rejects(job('load',{ownerId:invited}), /denied/);
    assert.equal((await job('load',{ownerId:owner})).document.positions.length,1);
    assert.deepEqual(await job('owners'),[{id:owner,personalFeed:true}]);
    await db.exec(`reset role; update terminal_members set enabled=false where email='rahulkanotra1101@gmail.com'`);
    await assert.rejects(job('load',{ownerId:owner}), /access/);
  } finally { await db.close(); }
});
